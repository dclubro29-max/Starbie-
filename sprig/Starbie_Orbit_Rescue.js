// One-button gameplay: W to jump, W again in the air for a double jump.
// W restarts after game over. Designed for the Sprig hardware.
const hazards=[C,R,B,F];
let score=0, best=0, level=1, coins=0, lives=3, shield=0;
let combo=0, ticks=0, jumpTicks=0, airJumps=0, invincible=0;
let gap=8, pace=190, running=false, timer=null, message="", messageTicks=0;
function say(t,n){message=t;messageTicks=n;}
function hud(){
  clearText();
  addText("S "+score+" BEST "+best,{x:0,y:0,color:color`0`});
  addText("LV "+level+" HP "+lives+" C "+coins,{x:0,y:1,color:color`0`});
  if(shield>0)addText("SHIELD "+shield,{x:0,y:2,color:color`0`});
  if(messageTicks>0)addText(message,{x:1,y:4,color:color`0`});
  if(!running){
    addText("GAME OVER",{x:4,y:6,color:color`3`});
    addText("W TO RESTART",{x:2,y:8,color:color`0`});
  }
}
function restart(){
  if(timer!==null)clearInterval(timer);
  setMap(scene);
  addSprite(2,9,D);
  addSprite(5,2,H);
  addSprite(12,3,H);
  score=0;level=1;coins=0;lives=3;shield=0;
  combo=0;ticks=0;jumpTicks=0;airJumps=0;invincible=0;
  gap=8;pace=190;running=true;
  say("W JUMP TWICE",16);
  hud();
  timer=setInterval(step,pace);
}
onInput("w",()=>{
  if(!running){restart();return;}
  if(jumpTicks===0){
    jumpTicks=6;
    airJumps=1;
  }else if(airJumps===1){
    jumpTicks=5;
    airJumps=2;
    say("DOUBLE JUMP",5);
  }
});
function moveSprites(){
  for(const type of [C,R,B,F,O,Q,U,H]){
    for(const item of getAll(type)){
      if(item.x===0){
        item.remove();
        if(hazards.includes(type)){
          combo++;
          score+=5+Math.min(20,combo);
        }
      }else item.x--;
    }
  }
}
function collect(hero){
  for(const item of getTile(hero.x,hero.y)){
    if(item.type===O){
      item.remove();coins++;score+=20;
      if(coins%5===0){shield++;say("BONUS SHIELD",9);}
    }else if(item.type===Q){
      item.remove();shield++;say("SHIELD +1",9);
    }else if(item.type===U){
      item.remove();score+=50;say("BONUS +50",9);
    }
  }
}
function damage(hero){
  if(invincible>0)return;
  const tile=getTile(hero.x,hero.y);
  const enemy=tile.find(item=>hazards.includes(item.type));
  if(!enemy)return;
  enemy.remove();
  invincible=8;
  combo=0;
  if(shield>0){shield--;say("SHIELD SAVE",10);}
  else{
    lives--;
    say("OUCH HP "+lives,10);
    if(lives<=0){
      running=false;
      if(score>best)best=score;
    }
  }
}
function spawn(){
  const choice=Math.floor(Math.random()*4);
  const kind=hazards[choice];
  addSprite(15,kind===F?8:9,kind);
  const roll=Math.random();
  if(roll<0.65)addSprite(15,7,O);
  else if(roll<0.72)addSprite(15,7,Q);
  else if(roll<0.79)addSprite(15,7,U);
  gap=Math.max(6,10-Math.floor(level/2))+Math.floor(Math.random()*3);
}
function step(){
  if(!running)return;
  ticks++;
  const hero=getFirst(D);
  if(!hero)return;
  if(jumpTicks>0){
    hero.y=jumpTicks>=5?8:jumpTicks>=3?7:jumpTicks===2?8:9;
    jumpTicks--;
  }else{
    hero.y=9;
    airJumps=0;
  }
  moveSprites();
  collect(hero);
  if(invincible>0)invincible--;
  damage(hero);
  if(!running){hud();return;}
  if(ticks%2===0)score++;
  if(score>best)best=score;
  const nextLevel=1+Math.floor(score/120);
  if(nextLevel>level){
    level=nextLevel;
    say("LEVEL "+level,12);
    if(level%3===0){lives=Math.min(5,lives+1);say("EXTRA LIFE",12);}
  }
  if(ticks%18===0)addSprite(15,2+(ticks%2),H);
  gap--;
  if(gap<=0)spawn();
  const nextPace=Math.max(82,190-(level-1)*10);
  if(nextPace!==pace){
    pace=nextPace;
    clearInterval(timer);
    timer=setInterval(step,pace);
  }
  if(messageTicks>0)messageTicks--;
  hud();
}
restart();
